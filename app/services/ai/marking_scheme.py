from __future__ import annotations

import json
import re
from decimal import Decimal

from pydantic import BaseModel, Field, ValidationError, field_validator, model_validator

from app.services.ai.llm import LLMService


class GeneratedMarkingFactor(BaseModel):
    name: str = Field(min_length=2, max_length=100)
    description: str = Field(min_length=3, max_length=1000)
    weight_percent: Decimal = Field(gt=0, le=25)

    @field_validator("name", "description")
    @classmethod
    def clean_text(cls, value: str) -> str:
        return value.strip()


class GeneratedMarkingScheme(BaseModel):
    factors: list[GeneratedMarkingFactor] = Field(
        min_length=1,
        max_length=10,
    )

    @model_validator(mode="after")
    def validate_total(self):
        total = sum(
            (f.weight_percent for f in self.factors),
            Decimal("0"),
        )

        if total != Decimal("25"):
            raise ValueError(
                f"Generated marking factors must total exactly 25 percent, "
                f"but received {total}"
            )

        return self


class MarkingSchemeGenerationError(RuntimeError):
    pass


SYSTEM_PROMPT = """You are a university exam marking-scheme assistant.

Your job is to generate ONLY teacher-controlled additional marking factors
for an exam question.

The approved reference answer is the academic baseline and accounts for
exactly 75% of the marks.

The additional marking factors generated by you account for exactly the
remaining 25%.

Factors may cover question-specific observable criteria such as:
- diagrams
- handwriting/readability
- working/steps
- examples
- structure
- notation
- presentation
- organization

Factors must be relevant to the specific question.

Do NOT duplicate academic correctness already represented by the 75% baseline.

STRICT JSON OUTPUT RULES:
- Return exactly one JSON object.
- Return valid RFC-compliant JSON.
- Do not use Markdown.
- Do not use ```json or any other code fence.
- Do not add explanations before or after the JSON.
- All newline characters inside JSON strings MUST be escaped as \\n.
- All tab characters inside JSON strings MUST be escaped as \\t.
- Double quotes inside JSON strings MUST be escaped as \\\".

The JSON object MUST have exactly this structure:

{
  "factors": [
    {
      "name": "string",
      "description": "string",
      "weight_percent": 10
    }
  ]
}

STRICT WEIGHT RULES:
- Generate between 2 and 5 factors.
- Every weight_percent must be greater than 0.
- Every weight_percent must be at most 25.
- The sum of ALL weight_percent values MUST be exactly 25.
- Use simple numeric values such as 5, 10, 15, or 12.5.
"""


class MarkingSchemeAgent:
    def __init__(self, llm: LLMService | None = None) -> None:
        self.llm = llm or LLMService()

    def generate(
        self,
        *,
        question_text: str,
        max_marks: int,
        baseline_answer: str,
        key_concepts: list[str],
    ) -> GeneratedMarkingScheme:

        prompt = f"""Generate the additional marking factors for this exam question.

Question ({max_marks} marks):
{question_text}

Approved baseline answer:
{baseline_answer}

Key concepts:
{', '.join(key_concepts) or 'None'}

Generate 2-5 relevant additional marking factors.

The factors MUST total exactly 25 percent.

Return ONLY the JSON object.
"""

        response = self.llm.chat(
            system_prompt=SYSTEM_PROMPT,
            user_prompt=prompt,
            temperature=0.1,
            max_tokens=1000,
        )

        try:
            payload = self._parse_json(response.content)

            return GeneratedMarkingScheme.model_validate(payload)

        except json.JSONDecodeError as exc:
            print("========== MARKING SCHEME JSON ERROR ==========")
            print("JSON error:", exc)
            print("Error position:", exc.pos)
            print("Error line:", exc.lineno)
            print("Error column:", exc.colno)
            print("Raw response repr:")
            print(repr(response.content))
            print("===============================================")

            raise MarkingSchemeGenerationError(
                "The LLM returned invalid JSON for the marking scheme"
            ) from exc

        except ValidationError as exc:
            print("========== MARKING SCHEME VALIDATION ERROR ==========")
            print("Raw response:")
            print(response.content)
            print("Validation error:")
            print(exc)
            print("======================================================")

            raise MarkingSchemeGenerationError(
                "The LLM returned a marking scheme that does not match the required structure"
            ) from exc

        except TypeError as exc:
            print("========== MARKING SCHEME TYPE ERROR ==========")
            print("Raw response:")
            print(response.content)
            print("===============================================")

            raise MarkingSchemeGenerationError(
                "The LLM returned an invalid marking-scheme structure"
            ) from exc

    @staticmethod
    def _parse_json(content: str) -> dict:
        cleaned = content.strip()

        # Remove Markdown code fences if the model ignores the instruction.
        if cleaned.startswith("```"):
            cleaned = re.sub(
                r"^```(?:json)?\s*",
                "",
                cleaned,
                flags=re.IGNORECASE,
            )

            cleaned = re.sub(
                r"\s*```$",
                "",
                cleaned,
            ).strip()

        # First attempt: parse the response exactly as returned.
        try:
            payload = json.loads(cleaned)

        except json.JSONDecodeError:
            # Some LLMs return literal newline/tab characters inside
            # JSON strings. Repair only those characters while preserving
            # the actual JSON structure.
            repaired = MarkingSchemeAgent._repair_json_control_chars(
                cleaned
            )

            payload = json.loads(repaired)

        if not isinstance(payload, dict):
            raise TypeError(
                "The LLM response must be a JSON object"
            )

        return payload

    @staticmethod
    def _repair_json_control_chars(content: str) -> str:
        """
        Escape literal JSON control characters occurring inside strings.

        JSON does not allow raw newline, carriage return, tab, backspace,
        or form-feed characters inside quoted strings.

        JSON structural characters outside strings are left untouched.
        """

        result: list[str] = []

        in_string = False
        escaped = False

        for char in content:
            if escaped:
                result.append(char)
                escaped = False
                continue

            if char == "\\":
                result.append(char)
                escaped = True
                continue

            if char == '"':
                result.append(char)
                in_string = not in_string
                continue

            if in_string:
                if char == "\n":
                    result.append("\\n")
                    continue

                if char == "\r":
                    result.append("\\r")
                    continue

                if char == "\t":
                    result.append("\\t")
                    continue

                if char == "\b":
                    result.append("\\b")
                    continue

                if char == "\f":
                    result.append("\\f")
                    continue

            result.append(char)

        return "".join(result)